// ---------- body block renderer ----------
function renderBody(blocks, lang) {
  const x = (v) => tr(v, lang).replace(/\{\{path:([a-z0-9-]+)\}\}/g, (_, slug) => {
    const p = pathFor(slug, lang);
    if (!p) throw new Error(`build-pages: unknown {{path:${slug}}}`);
    return p;
  });
  return blocks
    .map((b) => {
      if (b.diagram) return diagramHtml(b.diagram, lang);
      if (b.calculator) return calculatorHtml(lang);
      if (b.h2) return `<h2>${x(b.h2)}</h2>`;
      if (b.p) return `<p>${x(b.p)}</p>`;
      if (b.ul) return `<ul>\n${b.ul.map((i) => `  <li>${x(i)}</li>`).join('\n')}\n</ul>`;
      if (b.ol) return `<ol>\n${b.ol.map((i) => `  <li>${x(i)}</li>`).join('\n')}\n</ol>`;
      if (b.code) return `<pre><code>${esc(b.code)}</code></pre>`;
      if (b.callout) return `<div class="callout">\n  <p>${x(b.callout)}</p>\n</div>`;
      if (b.table) {
        const head = b.table.head.map((h) => `<th scope="col">${x(h)}</th>`).join('');
        const rows = b.table.rows.map((r) => `    <tr>${r.map((c) => `<td>${x(c)}</td>`).join('')}</tr>`).join('\n');
        return `<div class="table-wrap">\n<table>\n  <thead><tr>${head}</tr></thead>\n  <tbody>\n${rows}\n  </tbody>\n</table>\n</div>`;
      }
      throw new Error('build-pages: unknown block ' + Object.keys(b));
    })
    .join('\n');
}

// Internal linking: declared related + pages that link back to this one + shared tags (deterministic, max n)
function autoRelated(page, n) {
  const all = [...SERIES, ...NOTES, ...CASES].filter((p) => p.slug !== page.slug);
  const score = new Map(all.map((p) => [p.slug, 0]));
  for (const r of page.related ?? []) if (score.has(r)) score.set(r, score.get(r) + 100);
  for (const p of all) if ((p.related ?? []).includes(page.slug)) score.set(p.slug, score.get(p.slug) + 50);
  for (const p of all) {
    const shared = (p.tags ?? []).filter((x) => (page.tags ?? []).includes(x)).length;
    score.set(p.slug, score.get(p.slug) + shared * 5);
  }
  const hit = all.filter((p) => score.get(p.slug) > 0).sort((a, b) => score.get(b.slug) - score.get(a.slug) || a.slug.localeCompare(b.slug));
  return hit.slice(0, n).map((p) => p.slug);
}
