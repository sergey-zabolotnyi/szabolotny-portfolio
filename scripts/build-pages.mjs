// ---------- sitemap block ----------
function sitemapBlock() {
  const entry = (path, prio, date, alts = []) =>
    `  <url>\n    <loc>${SITE + path}</loc>\n    <lastmod>${date}</lastmod>\n    <priority>${prio}</priority>\n` +
    alts.map((a) => `    <xhtml:link rel="alternate" hreflang="${a.hreflang}" href="${SITE + a.path}"/>\n`).join('') +
    `  </url>\n`;
  const idxAlts = [...LANGS.map((l) => ({ hreflang: LANG[l].hreflang, path: indexPath(l) })), { hreflang: 'x-default', path: indexPath('de') }];
  let out = '';
  for (const c of CASES) out += entry(c.path, '0.8', '2026-10-25');
  for (const l of LANGS) out += entry(indexPath(l), l === 'de' ? '0.7' : '0.6', '2026-10-25', idxAlts);
  for (const s of SERIES) for (const l of LANGS) out += entry(seriesPath(s.slug, l), l === 'de' ? '0.7' : '0.6', s.date, alternatesFor(s.slug));
  for (const n of NOTES) out += entry(n.path, '0.6', n.date);
  return `${SM_START}\n${out}${SM_END}\n`;
}
function sitemapFile() {
  const file = join(ROOT, 'sitemap.xml');
  let s = readFileSync(file, 'utf8');
  const block = sitemapBlock();
  if (s.includes(SM_START)) s = s.replace(new RegExp(`${SM_START}[\\s\\S]*?${SM_END}\\n`), block);
  else s = s.replace('</urlset>', block + '</urlset>');
  return [file, s];
}

// ---------- internal link check ----------
function checkLinks() {
  const known = new Set(outputs.map(([rel]) => '/' + rel.replace(/index\.html$/, '')));
  const bad = [];
  for (const [rel, html] of outputs) {
    for (const m of html.matchAll(/href="(\/[^"#?]*)/g)) {
      const p = m[1];
      if (p.startsWith('/_vercel')) continue;
      const ok = known.has(p) || existsSync(join(ROOT, p, p.endsWith('/') ? 'index.html' : '')) || existsSync(join(ROOT, p));
      if (!ok) bad.push(`${rel} → ${p}`);
    }
  }
  return bad;
}

// ---------- main ----------
const stale = [];
for (const [rel, html] of outputs) {
  const file = join(ROOT, rel);
  if (CHECK) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== html) stale.push(rel);
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, html);
    console.log(`✓ ${rel}`);
  }
}
const [smFile, smText] = sitemapFile();
if (CHECK) {
  if (readFileSync(smFile, 'utf8') !== smText) stale.push('sitemap.xml');
} else {
  writeFileSync(smFile, smText);
  console.log('✓ sitemap.xml');
}

