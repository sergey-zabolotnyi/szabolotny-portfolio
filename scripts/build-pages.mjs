#!/usr/bin/env node
// Generates case-study pages (/projekte/<slug>/) and engineering-note pages (/notizen/<slug>/, /notizen/)
// from content/pages.mjs.
//
//   node scripts/build-pages.mjs          -> (re)write the pages
//   node scripts/build-pages.mjs --check  -> exit 1 if committed pages are out of date (used in CI)
//
// Also checks that every page is listed in sitemap.xml. No dependencies — plain Node 18+.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { AUTHOR, CASES, NOTES } from '../content/pages.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://zabolotny.de';
const CHECK = process.argv.includes('--check');
const OG_IMAGE = `${SITE}/assets/og-image.png`;
const BANNER = '<!-- GENERATED by scripts/build-pages.mjs from content/pages.mjs — do not edit by hand -->';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escAttr = (s) => esc(s).replace(/"/g, '&quot;');
const ld = (obj) => `<script type="application/ld+json">\n${JSON.stringify(obj, null, 2)}\n</script>`;

const authorLd = { '@type': 'Person', name: AUTHOR.name, url: AUTHOR.url };

function head({ title, description, path, type = 'article', extra = '' }) {
  const url = SITE + path;
  return `<!DOCTYPE html>
${BANNER}
<html lang="de">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${esc(title)}</title>
<meta name="description" content="${escAttr(description)}">
<meta name="author" content="${AUTHOR.name}">
<meta name="robots" content="index, follow">
<link rel="canonical" href="${url}">
<link rel="icon" href="/favicon.ico" sizes="48x48">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<meta property="og:type" content="${type}">
<meta property="og:url" content="${url}">
<meta property="og:title" content="${escAttr(title)}">
<meta property="og:description" content="${escAttr(description)}">
<meta property="og:image" content="${OG_IMAGE}">
<meta property="og:locale" content="de_DE">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${escAttr(title)}">
<meta name="twitter:description" content="${escAttr(description)}">
<meta name="twitter:image" content="${OG_IMAGE}">
<meta name="theme-color" content="#0047AB">
<link rel="preload" href="/assets/fonts/syne-latin-800-normal.woff2" as="font" type="font/woff2" crossorigin>
<link rel="preload" href="/assets/fonts/dm-sans-latin-400-normal.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="/css/fonts.css">
<link rel="stylesheet" href="/css/page.css">
${extra}
<script defer src="/_vercel/insights/script.js"></script>
</head>
<body>
<header class="topbar">
  <a href="/">← zabolotny.de</a>
  <nav aria-label="Navigation">
    <a href="/#featured-cases">Projekte</a>
    <a href="/notizen/">Notizen</a>
    <a href="/#contact">Kontakt</a>
  </nav>
</header>
<main class="wrap">`;
}

const foot = `</main>
<footer>
  <span>© 2026 ${AUTHOR.name} · Dresden</span>
  <span><a href="/impressum.html">Impressum</a> · <a href="/datenschutz.html">Datenschutz</a></span>
</footer>
</body>
</html>
`;

const breadcrumbLd = (items) => ({
  '@context': 'https://schema.org',
  '@type': 'BreadcrumbList',
  itemListElement: items.map(([name, path], i) => ({
    '@type': 'ListItem',
    position: i + 1,
    name,
    item: SITE + path,
  })),
});

const tagsHtml = (tags) => `<ul class="tags">${tags.map((t) => `<li>${esc(t)}</li>`).join('')}</ul>`;

function casePage(c) {
  const app = { '@context': 'https://schema.org', ...c.jsonld, author: authorLd };
  const crumbs = [
    ['Start', '/'],
    ['Projekte', '/#featured-cases'],
    [c.slug === 'meistermeld' ? 'MeisterMeld' : 'PflegeOasis', c.path],
  ];
  return (
    head({
      title: c.title,
      description: c.description,
      path: c.path,
      extra: ld(app) + '\n' + ld(breadcrumbLd(crumbs)),
    }) +
    `
<p class="crumbs"><a href="/">Start</a> / <a href="/#featured-cases">Projekte</a> / ${esc(crumbs[2][0])}</p>
<p class="kicker">${esc(c.kicker)}</p>
<h1>${esc(c.h1)}</h1>
<p class="lead">${esc(c.lead)}</p>
<dl class="facts">
${c.facts.map(([k, v]) => `  <div><dt>${esc(k)}</dt><dd>${esc(v)}</dd></div>`).join('\n')}
</dl>
${tagsHtml(c.tags)}
${c.body}
<section class="cta">
  <h2>Mehr sehen oder sprechen</h2>
  <p>Ich suche eine Festanstellung als Fullstack-/KI-Entwickler mit DevOps-Schwerpunkt und bin offen für passende Projekte.</p>
  <a class="btn primary" href="${c.liveUrl}" target="_blank" rel="noopener noreferrer">${esc(c.liveLabel)} ↗</a>
  <a class="btn" href="/#contact">Kontakt aufnehmen</a>
  ${c.related.map((r) => `<a class="btn" href="${r.href}">${esc(r.label)}</a>`).join('\n  ')}
</section>
` +
    foot
  );
}

function notePage(n) {
  const article = {
    '@context': 'https://schema.org',
    '@type': 'TechArticle',
    headline: n.h1,
    description: n.description,
    datePublished: n.date,
    dateModified: n.date,
    inLanguage: 'de',
    image: OG_IMAGE,
    keywords: n.tags.join(', '),
    author: authorLd,
    mainEntityOfPage: SITE + n.path,
  };
  const crumbs = [
    ['Start', '/'],
    ['Notizen', '/notizen/'],
    [n.h1, n.path],
  ];
  return (
    head({
      title: `${n.title} | Serge Zabolotny`,
      description: n.description,
      path: n.path,
      extra: ld(article) + '\n' + ld(breadcrumbLd(crumbs)),
    }) +
    `
<p class="crumbs"><a href="/">Start</a> / <a href="/notizen/">Notizen</a></p>
<p class="kicker">${esc(n.kicker)}</p>
<h1>${esc(n.h1)}</h1>
<p class="lead">${esc(n.lead)}</p>
<p class="byline">${AUTHOR.name} · <time datetime="${n.date}">${n.date.split('-').reverse().join('.')}</time></p>
${tagsHtml(n.tags)}
${n.body}
<section class="cta">
  <h2>Mehr aus der Praxis</h2>
  <p>Weitere Notizen, Case Studies und Projekte findest du auf der Startseite.</p>
  <a class="btn primary" href="/notizen/">Alle Notizen</a>
  <a class="btn" href="/projekte/meistermeld/">Case Study MeisterMeld</a>
  <a class="btn" href="/projekte/pflegeoasis/">Case Study PflegeOasis</a>
</section>
` +
    foot
  );
}

function indexPage() {
  const path = '/notizen/';
  const title = 'Engineering Notes: DevOps, CI/CD, Zero Trust & KI aus der Praxis | Serge Zabolotny';
  const description =
    'Praxisnotizen von Serge Zabolotny, Fullstack- & KI-Entwickler in Dresden: Zero Trust mit Cloudflare, CI/CD für Next.js auf dem VPS, KI-Content mit Human-in-the-Loop.';
  const blog = {
    '@context': 'https://schema.org',
    '@type': 'CollectionPage',
    name: 'Engineering Notes',
    description,
    url: SITE + path,
    inLanguage: 'de',
    author: authorLd,
    hasPart: NOTES.map((n) => ({ '@type': 'TechArticle', headline: n.h1, url: SITE + n.path, datePublished: n.date })),
  };
  const crumbs = [
    ['Start', '/'],
    ['Notizen', path],
  ];
  return (
    head({
      title,
      description,
      path,
      type: 'website',
      extra: ld(blog) + '\n' + ld(breadcrumbLd(crumbs)),
    }) +
    `
<p class="crumbs"><a href="/">Start</a> / Notizen</p>
<p class="kicker">Engineering Notes</p>
<h1>DevOps, CI/CD, Zero Trust und KI – Notizen aus der Praxis</h1>
<p class="lead">Konkrete Probleme, Entscheidungen und Ergebnisse aus meinen Projekten: kurz, ehrlich und nachvollziehbar.</p>
<div class="cards">
${NOTES.map(
  (n) => `  <a class="card" href="${n.path}">
    <p class="kicker">${esc(n.kicker)}</p>
    <h2>${esc(n.h1)}</h2>
    <p>${esc(n.lead)}</p>
  </a>`
).join('\n')}
</div>
<section class="cta">
  <h2>Weitere Notizen</h2>
  <p>Kürzere Notizen zu Proxmox, Telegram-Bots, Groq und mehr stehen in der Notizen-Sektion der Startseite.</p>
  <a class="btn primary" href="/#blog">Zur Startseite</a>
</section>
` +
    foot
  );
}

// ---------- main ----------
const outputs = [
  ['notizen/index.html', indexPage()],
  ...CASES.map((c) => [`projekte/${c.slug}/index.html`, casePage(c)]),
  ...NOTES.map((n) => [`notizen/${n.slug}/index.html`, notePage(n)]),
];

const stale = [];
for (const [rel, html] of outputs) {
  const file = join(ROOT, rel);
  if (CHECK) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== html) stale.push(rel);
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, html);
    console.log(`✓ ${rel}`);
  }
}

// sitemap must list every generated page
const sitemap = readFileSync(join(ROOT, 'sitemap.xml'), 'utf8');
const unlisted = [CASES, NOTES].flat().map((p) => SITE + p.path).concat(SITE + '/notizen/').filter((u) => !sitemap.includes(`<loc>${u}</loc>`));
if (unlisted.length) {
  console.error(`✗ missing in sitemap.xml: ${unlisted.join(', ')}`);
  process.exit(1);
}

if (CHECK) {
  if (stale.length) {
    console.error(`✗ out of date: ${stale.join(', ')}\n  Run: node scripts/build-pages.mjs and commit the result.`);
    process.exit(1);
  }
  console.log('✓ content pages are up to date');
}
